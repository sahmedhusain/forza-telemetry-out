const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const dgram = require('node:dgram');
const net = require('node:net');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const { WebSocket } = require('ws');
async function freePort() { const socket = net.createServer(); await new Promise(resolve => socket.listen(0, '127.0.0.1', resolve)); const port = socket.address().port; await new Promise(resolve => socket.close(resolve)); return port; }
test('UDP → decoder → WebSocket, exports, stale status and origin protection', { timeout: 15000 }, async t => {
  const port = await freePort(); const udp = dgram.createSocket('udp4');
  await new Promise(resolve => udp.bind(0, '127.0.0.1', resolve)); const udpPort = udp.address().port; await new Promise(resolve => udp.close(resolve));
  const dataDir=fs.mkdtempSync(path.join(os.tmpdir(),'forza-network-'));
  const child = spawn(process.execPath, ['server/index.js'], { env: { ...process.env, FORZA_DATA_DIR:dataDir, WEB_PORT: String(port), FORZA_PORT: String(udpPort), WEB_HOST: '127.0.0.1', FORZA_HOST: '127.0.0.1' }, stdio: ['ignore', 'pipe', 'pipe'] });
  t.after(async()=>{const exited=new Promise(resolve=>child.once('exit',resolve));child.kill();if(child.exitCode===null)await exited;fs.rmSync(dataDir,{recursive:true,force:true});});
  await new Promise((resolve, reject) => { child.stdout.on('data', b => { if (b.toString().includes('DASHBOARD READY')) resolve(); }); child.once('exit', code => reject(Error(`Server exited ${code}`))); });
  const base = `http://127.0.0.1:${port}`;
  assert.equal((await fetch(base)).status, 200);
  assert.equal((await fetch(base+'/api/simulator/toggle',{method:'POST'})).status,404);
  assert.equal((await fetch(base+'/js/audio.js')).status,404);
  assert.equal((await fetch(base + '/api/recorder/start', { method: 'POST', headers: { Origin: 'https://evil.example' } })).status, 403);
  assert.equal((await fetch(base + '/api/recorder/start', { method: 'POST' })).status, 200);
  const ws = new WebSocket(base.replace('http:', 'ws:')); t.after(() => ws.terminate());
  await new Promise(resolve => ws.once('open', resolve));
  const framePromise = new Promise(resolve => ws.on('message', raw => { const msg = JSON.parse(raw); if (msg.type === 'telemetry') resolve(msg.data); }));
  const sender = dgram.createSocket('udp4'); t.after(() => sender.close());
  const buffer = Buffer.alloc(324); buffer.writeInt32LE(1,0); buffer.writeFloatLE(42, 256); buffer.writeInt32LE(1, 132); buffer.writeFloatLE(25, 240);
  sender.send(buffer, udpPort, '127.0.0.1'); const frame = await framePromise;
  const history=await(await fetch(base+'/api/history')).json();assert.equal(history.profile.packets,1);assert.equal(history.profile.bounds.Speed.max,42);
  assert.equal(frame.speed.mps, 42); assert.equal(frame.raw.WheelInPuddleFrontLeft, 1); assert.equal(frame.collision.mass, 25);
  await fetch(base + '/api/recorder/stop', { method: 'POST' });
  assert.equal((await fetch(base + '/api/recorder/start', { method: 'POST' })).status, 409);
  const csv = await (await fetch(base + '/api/recorder/export/csv')).text(); assert.equal(csv.trim().split('\n').length, 2);
  await new Promise(resolve => setTimeout(resolve, 2200));
  const status = await (await fetch(base + '/api/status')).json(); assert.equal(status.udp.hasActiveStream, false);
  await fetch(base + '/api/recorder/clear', { method: 'POST' });
  assert.equal((await fetch(base + '/api/recorder/start', { method: 'POST' })).status, 200);
  const change = port => fetch(base+'/api/connection',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({port})});
  assert.equal((await change(5601)).status,409);
  await fetch(base+'/api/recorder/stop',{method:'POST'});
  assert.equal((await change(5250)).status,400);
  const occupied=dgram.createSocket('udp4');await new Promise(r=>occupied.bind(0,'127.0.0.1',r));
  assert.equal((await change(occupied.address().port)).status,400);occupied.close();
  assert.equal((await (await fetch(base+'/api/network')).json()).udpPort,udpPort);
  const next=await freePort();assert.equal((await change(next)).status,200);
  assert.equal((await (await fetch(base+'/api/network')).json()).udpPort,next);
  assert.ok((await (await fetch(base+'/api/config/download')).text()).includes('FORZA_PORT='+next));
});
